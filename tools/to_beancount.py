#!/usr/bin/env python3
"""Write ledger/main.beancount for oldbill.bucklerfamily.estate from the loss heads in damages.py (+ the £0 order lines in build.py).
Same engine and conventions as accounts.bucklerfamily.estate: plain-text Beancount, GBP, renamed roots so it can never be mixed
with cash (Borne = carried by Team Williams, Caused = the balancing memo, Liable = Team Regime if the case is reopened).
Reopen postings are separate transactions tagged #reopen and linked to their head (^L-xxx); build.py leaves them out of the
'now' books and adds them for the 'reopened' books.
Run after any change to damages.py figures:  python3 tools/to_beancount.py && bean-check ledger/main.beancount && python3 tools/build.py
— Sion's Tab agent"""
import json, pathlib, sys
from decimal import Decimal
HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
LEDGER = (HERE / 'site' / 'ledger') if (HERE / 'site').exists() else (HERE.parent / 'ledger')
import build as B
DMG = B.DMG
OPEN = '2026-10-22'

def q(s): return '"' + str(s).replace('\\', '\\\\').replace('"', '\\"') + '"'
def gbp(x): return '%s GBP' % Decimal(str(round(float(x), 2))).quantize(Decimal('0.01'))

def main():
    accts = set(); txns = []
    for c in B.COSTS:
        amt = round(c['amount'], 2); d = c.get('date', OPEN)
        meta = [('id', c['id']), ('group', c['group']), ('status', c['status']), ('estimate', 'yes' if c.get('estimate') else 'no')]
        if c.get('nil'): meta.append(('nil', 'yes'))
        if 'low' in c: meta += [('low', c['low']), ('high', c['high'])]
        if c.get('alloc'): meta.append(('alloc', ', '.join('%s %d' % kv for kv in c['alloc'].items())))
        if 'causation' in c: meta.append(('causation', c['causation'] if c['causation'] is not None else ''))
        meta.append(('basis', c['basis']))
        for i, s in enumerate(c['sources'], 1): meta.append(('source%d' % i, s['title'] + ' | ' + (s['url'] or '')))
        borne = 'Borne:Team-Williams:' + c['account']; caused = 'Caused:' + c['account']; accts |= {borne, caused}
        L = ['%s * "Team Williams" %s ^%s' % (d, q(c['head']), c['id'])] + ['  %s: %s' % (k, q(v)) for k, v in meta]
        L += ['  %s   %s' % (borne, gbp(amt)), '  %s   %s' % (caused, gbp(-amt))]
        txns.append('\n'.join(L))
        if c['status'] == 'contingent' and amt > 0:
            pennies = int(round(amt * 100)); parts = []; used = 0
            for a, share in c['alloc'].items():
                p = pennies * share // 100; parts.append([a, p]); used += p
            parts[0][1] += pennies - used
            R = ['%s * "Team Regime" %s #reopen ^%s' % (d, q('If reopened: ' + c['head']), c['id']), '  id: %s' % q(c['id'])]
            for a, p in parts:
                acc = 'Liable:Team-Regime:' + a; accts.add(acc); R.append('  %s   %s' % (acc, gbp(p / 100)))
            R.append('  %s   %s' % (borne, gbp(-amt)))
            txns.append('\n'.join(R))
    for k, p in DMG.PARTIES.items(): accts.add('Liable:Team-Regime:' + k)
    head = ['; Old Bill — who gained, who lost: the double-entry ledger of the loss heads at mid (analyst compensatory build-up).',
            '; Generated by tools/to_beancount.py from damages.py; converted 1:1 from the oldbill-ledger/1 tables on 23 Oct 2026.',
            '; Roots renamed so this memo can never be mixed with cash (the accounts.bucklerfamily.estate convention).',
            'option "title" "Old Bill — loss heads (Team Williams / Team Regime)"', 'option "operating_currency" "GBP"',
            'option "name_assets" "Borne"', 'option "name_equity" "Caused"', 'option "name_liabilities" "Liable"', '']
    parties = ['%s custom "party" %s %s %s' % (OPEN, q('Liable:Team-Regime:' + k), q(p['name']), q(p['route'])) for k, p in DMG.PARTIES.items()]
    opens = ['%s open %s GBP' % ('1900-01-01', a) for a in sorted(accts)]
    LEDGER.mkdir(parents=True, exist_ok=True)
    (LEDGER / 'main.beancount').write_text('\n'.join(head + opens + [''] + parties + [''] + ['\n\n'.join(txns)]) + '\n')
    print('wrote', LEDGER / 'main.beancount', len(txns), 'transactions')

if __name__ == '__main__': main()
