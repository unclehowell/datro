async function routeToKiro(task) {
  // kiro-cli (npm: @aws/kiro-cli) takes a chat subcommand; run it
  // headless with trust-all-tools so agentic prompts execute end-to-end.
  const run = () =>
    runBackend({
      bin: KIRO_BIN,
      args: ["chat", "--no-interactive", "--trust-all-tools", task],
      label: "kiro",
      timeoutMs: 300_000,
      env: { ...process.env, NONINTERACTIVE: "1", AGENT_TOOL_ACCESS: "full" },
    });
  const out = await run();
  return backendOutput(out, "kiro");
}

async function routeTask(task) {
  // WS-08: ledger the run BEFORE dispatching so a crash mid-task leaves a
  // recoverable record (GET /ledger). Cleared on every terminal outcome.
  const taskId = ledgerTaskId();
  const startedAt = Date.now();
  const base = { id: taskId, task, startedAt };
  ledgerWrite({ ...base, backend: "opencode", status: "running" });

  // Try opencode first (primary agentic backend)
  try {
    const result = await routeToOpencode(task);
    ledgerClear(taskId);
    return { backend: "opencode", result };
  } catch (err) {
    ledgerWrite({ ...base, backend: "kilo", status: "running", note: `opencode failed: ${err.message}` });
    console.log(`[task-router] opencode failed: ${err.message}, trying kilo...`);
  }

  // Fallback to kilo
  try {
    const result = await routeToKilo(task);
    ledgerClear(taskId);
    return { backend: "kilo", result };
  } catch (err) {
    ledgerWrite({ ...base, backend: "kiro", status: "running", note: `kilo failed: ${err.message}` });
    console.log(`[task-router] kilo failed: ${err.message}, trying kiro...`);
  }

  // Final fallback to kiro (AWS kiro-cli)
  try {
    const result = await routeToKiro(task);
    ledgerClear(taskId);
    return { backend: "kiro", result };
  } catch (err) {
    ledgerWrite({ ...base, backend: "none", status: "failed", note: err.message });
    console.log(`[task-router] kiro failed: ${err.message}`);
    return { backend: "none", result: "No agentic backend available. Install opencode, kilo, or kiro." };
  }
}

// HTTP server for task routing API
const server = http.createServer(async (req, res) => {
  // CORS
  res.setHeader("Access-Control-Allow-Origin", "*");
  res.setHeader("Access-Control-Allow-Methods", "GET, POST, OPTIONS");
  res.setHeader("Access-Control-Allow-Headers", "Content-Type");

  if (req.method === "OPTIONS") {
    res.writeHead(204);
    res.end();
    return;
  }

  if (req.method === "GET" && req.url === "/health") {
    res.writeHead(200, { "Content-Type": "application/json" });
    res.end(JSON.stringify({ 
      status: "ok",
      backends: {
        opencode: await checkBinary(OPENCODE_BIN),
        kilo: await checkBinary(KILO_BIN),
        kiro: await checkBinary(KIRO_BIN),
      },
      inFlight: ledgerList().filter((e) => e.status === "running").length,
    }));
    return;
  }

  if (req.method === "GET" && req.url === "/ledger") {
    // WS-08: in-flight (non-terminal) task records, newest first — for crash
    // resume and for the GUI's tasks view.
    res.writeHead(200, { "Content-Type": "application/json" });
    res.end(JSON.stringify({ ledger: ledgerList().filter((e) => e.status !== "done" && e.status !== "failed") }));
    return;
  }

  if (req.method === "POST" && req.url === "/route") {
    // WS6: require the shared secret for /route when one is configured. The GUI
    // reads the same TASK_ROUTER_TOKEN (from ~/.fcukproxy/.env) and echoes it.
    if (ROUTER_TOKEN && `Bearer ${ROUTER_TOKEN}` !== (req.headers.authorization || "")) {
      res.writeHead(401, { "Content-Type": "application/json" });
      res.end(JSON.stringify({ error: "unauthorized" }));
      return;
    }
    let body = "";
    for await (const chunk of req) body += chunk;

    try {
      const { text, messages } = JSON.parse(body);
      const input = text || (messages?.length ? messages[messages.length - 1].content : "");

      if (!input) {
        res.writeHead(400, { "Content-Type": "application/json" });
        res.end(JSON.stringify({ error: "text or messages required" }));
        return;
      }

      const isTaskRequest = isTask(input);

      if (!isTaskRequest) {
        // Chat — route to ollama via OmniRoute
        res.writeHead(200, { "Content-Type": "application/json" });
        res.end(JSON.stringify({ type: "chat", backend: "ollama", input }));
        return;
      }

      // Task — route to agentic backend
      console.log(`[task-router] Task detected: "${input.slice(0, 80)}..."`);
      const { backend, result } = await routeTask(input);

      res.writeHead(200, { "Content-Type": "application/json" });
      res.end(JSON.stringify({ type: "task", backend, result }));
    } catch (err) {
      res.writeHead(500, { "Content-Type": "application/json" });
      res.end(JSON.stringify({ error: err.message }));
    }
    return;
  }

  res.writeHead(404, { "Content-Type": "application/json" });
  res.end(JSON.stringify({ error: "Not found" }));
});

async function checkBinary(name) {
  try {
    await execFileAsync("which", [name]);
    return true;
  } catch {
    return false;
  }
}

server.listen(PORT, HOST, () => {
  ledgerPrune();
  console.log(`[task-router] Running on http://${HOST}:${PORT}`);
  console.log(`[task-router] opencode: ${OPENCODE_BIN}`);
  console.log(`[task-router] kilo: ${KILO_BIN}`);
  console.log(`[task-router] kiro: ${KIRO_BIN}`);
  console.log(`[task-router] auth: ${ROUTER_TOKEN ? "required (shared secret)" : "loopback-only (no token configured)"}`);
});
